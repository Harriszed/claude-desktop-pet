// Import byte-for-byte exports from a pinned Mascot Studio tag; keep app state IDs stable.
const fs = require('fs'), path = require('path'), crypto = require('crypto')
const { execFileSync } = require('child_process')
const root = path.join(__dirname, '..')
const source = process.argv[2]
const ref = process.argv[3] || 'v1.7.0'
if (!source) throw new Error('Usage: node scripts/sync-animations.js <mascot-studio checkout> [tag]')
if (!/^v\d+\.\d+\.\d+$/.test(ref)) throw new Error('Use a version tag, for example v1.7.0')
const git = args => execFileSync('git', args, { cwd: source, maxBuffer: 32 * 1024 * 1024 })
const read = file => git(['show', `${ref}:${file}`])
const commit = git(['rev-parse', `${ref}^{}`]).toString().trim()
const manifest = JSON.parse(read('public/mascot/manifest.json'))
const pkg = JSON.parse(read('package.json'))
if (ref !== `v${pkg.version}`) throw new Error('Source tag and package version do not match')
const animations = manifest.states.filter(item => item.name.endsWith('-fluid') || item.name.startsWith('gag-'))
if (animations.filter(item => item.name.endsWith('-fluid')).length !== 22 || animations.filter(item => item.name.startsWith('gag-')).length !== 10) throw new Error('Expected all 22 activities and 10 gags')
const states = {}
// Validate every source before writing anything.
const imports = animations.map(item => {
  const id = item.name.replace(/-fluid$/, '')
  if (!/^[a-z-]+$/.test(id) || !(item.duration > 0)) throw new Error(`Invalid animation metadata: ${item.name}`)
  const bytes = read(`public/mascot/${item.file}`)
  if (!bytes.toString().includes(`data-state="${item.name}"`) || !bytes.toString().includes('prefers-reduced-motion')) throw new Error(`Invalid SVG export: ${item.file}`)
  states[id] = { sourceState: item.name, file: `${id}.svg`, duration: item.duration, loop: item.loop, sha256: crypto.createHash('sha256').update(bytes).digest('hex') }
  return { id, bytes, gif: id.startsWith('gag-') ? read(`public/mascot/gifs/${item.name}.gif`) : null }
})
// Keep the walk from before v1.7.0 when refreshing the rest of the collection.
const walkingTag = 'v1.6.0'
const walkingManifest = JSON.parse(git(['show', `${walkingTag}:public/mascot/manifest.json`]))
const walking = walkingManifest.states.find(item => item.name === 'walking-fluid')
const walkingBytes = git(['show', `${walkingTag}:public/mascot/${walking.file}`])
imports.find(item => item.id === 'walking').bytes = walkingBytes
states.walking = { sourceState: walking.name, file: 'walking.svg', duration: walking.duration, loop: walking.loop,
  sha256: crypto.createHash('sha256').update(walkingBytes).digest('hex'), sourceTag: walkingTag,
  sourceCommit: git(['rev-parse', `${walkingTag}^{}`]).toString().trim() }
// The sleeping story was replaced separately; retain its pinned source.
const asleepTag = 'v1.7.2'
const asleepManifest = JSON.parse(git(['show', `${asleepTag}:public/mascot/manifest.json`]))
const asleep = asleepManifest.states.find(item => item.name === 'asleep-fluid')
const asleepBytes = git(['show', `${asleepTag}:public/mascot/${asleep.file}`])
if (!asleepBytes.toString().includes(`data-state="${asleep.name}"`) || !asleepBytes.toString().includes('prefers-reduced-motion')) throw new Error('Invalid sleep SVG export')
imports.find(item => item.id === 'asleep').bytes = asleepBytes
states.asleep = { sourceState: asleep.name, file: 'asleep.svg', duration: asleep.duration, loop: asleep.loop,
  sha256: crypto.createHash('sha256').update(asleepBytes).digest('hex'), sourceTag: asleepTag,
  sourceCommit: git(['rev-parse', `${asleepTag}^{}`]).toString().trim() }
for (const item of imports) {
  fs.writeFileSync(path.join(root, 'assets', `${item.id}.svg`), item.bytes)
  if (item.gif) fs.writeFileSync(path.join(root, 'docs', 'gifs', `${item.id}.gif`), item.gif)
}
const catalog = { source: 'https://github.com/Harriszed/mascot-studio', version: pkg.version, tag: ref, commit, states }
fs.writeFileSync(path.join(root, 'animation-catalog.js'), `// Generated by scripts/sync-animations.js from Mascot Studio ${ref}.\n;(function () {\n  const catalog = ${JSON.stringify(catalog, null, 2)}\n  if (typeof module !== 'undefined' && module.exports) module.exports = catalog\n  else window.PET_ANIMATIONS = catalog\n})()\n`)
console.log(`Imported ${imports.length - 2} animations from ${ref} (${commit}), walking from ${walkingTag}, sleep from ${asleepTag}, and refreshed 10 README GIFs.`)
execFileSync(process.execPath, [path.join(__dirname, 'build-idle-animations.mjs'), source], { stdio: 'inherit' })
